#!/usr/bin/env node
'use strict'

const fs = require('fs')
const path = require('path')

const contractPath = path.resolve(
  __dirname,
  '../../backend/app/contracts/advanced_search_contract.json'
)
const outputPath = path.resolve(
  __dirname,
  '../src/contracts/advancedSearch.generated.ts'
)

function fail(message) {
  process.stderr.write(`[advanced-search-contract] ${message}\n`)
  process.exit(1)
}

const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'))
const operatorGroups = contract.operatorGroups

if (!operatorGroups || typeof operatorGroups !== 'object') {
  fail('operatorGroups must be an object')
}

const operatorMapping = {}
for (const [groupName, operators] of Object.entries(operatorGroups)) {
  if (!Array.isArray(operators)) {
    fail(`operatorGroups.${groupName} must be an array`)
  }
  for (const operator of operators) {
    if (
      !operator ||
      typeof operator.value !== 'string' ||
      typeof operator.label !== 'string' ||
      typeof operator.backendValue !== 'string'
    ) {
      fail(`operatorGroups.${groupName} contains an incomplete operator`)
    }
    const existing = operatorMapping[operator.value]
    if (existing && existing !== operator.backendValue) {
      fail(`operator ${operator.value} maps to conflicting backend values`)
    }
    operatorMapping[operator.value] = operator.backendValue
  }
}

const reverseOperatorMapping = {}
for (const [frontendValue, backendValue] of Object.entries(operatorMapping)) {
  if (!reverseOperatorMapping[backendValue]) {
    reverseOperatorMapping[backendValue] = frontendValue
  }
}

const stringify = value => JSON.stringify(value, null, 2)
const generated = `/* AUTO-GENERATED by scripts/generate-advanced-search-contract.js. DO NOT EDIT. */

export type AdvancedSearchFieldKind =
  | 'text'
  | 'number'
  | 'date'
  | 'select'
  | 'multiSelect'
  | 'boolean'

export interface AdvancedSearchOperatorConfig {
  value: string
  label: string
  backendValue: string
}

export interface AdvancedSearchFieldContract {
  kind: AdvancedSearchFieldKind
  operators: readonly string[]
}

export const ADVANCED_SEARCH_CONTRACT_VERSION = ${Number(contract.version)}
export const ADVANCED_SEARCH_MAX_REGEX_CONDITIONS = ${Number(contract.maxRegexConditions)}
export const ADVANCED_SEARCH_MAX_REGEX_PATTERN_LENGTH = ${Number(contract.maxRegexPatternLength)}

export const ADVANCED_SEARCH_FIELDS: Readonly<Record<string, AdvancedSearchFieldContract>> = Object.freeze(
${stringify(contract.fields)}
)

export const ADVANCED_SEARCH_OPERATOR_GROUPS: Readonly<
  Record<AdvancedSearchFieldKind, readonly AdvancedSearchOperatorConfig[]>
> = Object.freeze(
${stringify(operatorGroups)}
)

export const ADVANCED_SEARCH_OPERATOR_MAPPING: Readonly<Record<string, string>> = Object.freeze(
${stringify(operatorMapping)}
)

export const ADVANCED_SEARCH_REVERSE_OPERATOR_MAPPING: Readonly<Record<string, string>> = Object.freeze(
${stringify(reverseOperatorMapping)}
)

export const ADVANCED_SEARCH_NEGATED_OPERATORS: Readonly<Record<string, string>> = Object.freeze(
${stringify(contract.negatedOperators)}
)
`

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath)) {
    fail(`generated file is missing: ${outputPath}`)
  }
  if (fs.readFileSync(outputPath, 'utf8') !== generated) {
    fail('generated frontend contract is stale; run npm run contract:generate')
  }
  process.stdout.write('[advanced-search-contract] generated contract is current\n')
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  fs.writeFileSync(outputPath, generated, 'utf8')
  process.stdout.write(`[advanced-search-contract] wrote ${outputPath}\n`)
}
